_官方放假日 = {}
for _start, _end, _name in _放假区间:
    _day = date.fromisoformat(_start)
    _last = date.fromisoformat(_end)
    while _day <= _last:
        _官方放假日[_day] = _name
        _day += timedelta(days=1)


def 判定日期(day: date) -> tuple[str, str]:
    """返回日期性质和节日名；超出已核实年份不猜测。"""
    if not 2021 <= day.year <= 2026:
        return "未覆盖", ""
    if day in _补班日:
        return "工作日", ""
    if day in _官方放假日:
        return "官方放假日", _官方放假日[day]
    if day.weekday() >= 5:
        return "普通周末", ""
    return "工作日", ""