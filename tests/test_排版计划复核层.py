def test_结论汇总与排序(簿):
    结论 = 簿.取表("核对结论")
    项目 = 结论.表["项目"].tolist()
    # 追加行已写入
    assert "低风险事项数" in 项目 and "使用顺序" in 项目
    # 排序后第一行是"使用顺序"（visible 优先级 0）
    assert 项目[0] == "使用顺序"
    行号 = 项目.index("低风险事项数") + 2
    assert _值(结论, 行号, "数值") == "=COUNTIF('复核事项索引'!$E$2:$E$2,\"低风险\")"
    assert 结论.行[行号].隐藏          # 不在 visible 清单
    行号2 = 项目.index("期初余额状态") + 2
    assert not 结论.行[行号2].隐藏
    # 覆盖率：银行有总额出公式 + 百分比格式；序时账总额为 0 出常量 0
    行号3 = 项目.index("银行当前已对平金额覆盖率") + 2
    assert _值(结论, 行号3, "数值") == (
        "=SUMIF('核对明细'!$E$2:$E$2,\"银行流水\",'核对明细'!$J$2:$J$2)/100.0")
    assert 结论.覆盖[(行号3, 3)].数字格式 == "0.00%"
    行号4 = 项目.index("序时账当前已对平金额覆盖率") + 2
    assert _值(结论, 行号4, "数值") == 0
    # 已处理事项数以最后一次赋值为准
    行号5 = 项目.index("已处理事项数") + 2
    assert _值(结论, 行号5, "数值") == (
        "=COUNTIF('复核事项索引'!$H$2:$H$2,\"已记录核查结论*\")")
    # 追加区段是位置语义（旧代码排序只改写项目/数值两列已有的格）：
    # 原有末行之后的位置，A 列从未落格、项目列是 General 后建空格
    assert (2, 1) not in 结论.空缺格
    for r in range(3, len(结论.表) + 2):
        assert (r, 1) in 结论.空缺格
        assert 结论.覆盖[(r, 2)].数字格式 == "General"
    # 数值列的 General 随值走排序（低风险事项数是追加值，落位后数值格为 General）
    assert 结论.覆盖[(行号, 3)].数字格式 == "General"


