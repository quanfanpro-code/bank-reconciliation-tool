def test_整组核对结论替换与折叠(簿):
    base = "IFERROR(INDEX('复核事项索引'!$D$2:$D$2,MATCH(O2,'复核事项索引'!$C$2:$C$2,0)),\"\")"
    assert _值(簿.取表("整组核对"), 2, "当前核对结论") == (
        f'=SUBSTITUTE(SUBSTITUTE({base},"原对应被人工选择替代，记录未对应",'
        f'"原对应已被替代；展开查看各笔当前去向"),"原对应已否定，记录恢复未对应",'
        f'"原对应已否定；展开查看各笔当前去向")')
    整组 = 簿.取表("整组核对")
    assert 整组.行[3].outline == 1 and 整组.行[3].隐藏
    assert 整组.行[2].收起 and not 整组.行[3].收起
    assert 整组.冻结 == "C2" and 整组.筛选 is None
    assert 整组.outline汇总在下 is False and 整组.显示outline符号
    # 主行蓝底加粗、组成行浅蓝
    assert 整组.行[2].样式.填充色 == "DEEAF2" and 整组.行[2].样式.加粗
    assert 整组.行[3].样式.填充色 == "F3F7FA" and not 整组.行[3].样式.加粗


