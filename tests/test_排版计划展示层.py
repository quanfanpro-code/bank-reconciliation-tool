def test_逐笔核对结论公式(簿):
    o0 = "IFERROR(INDEX('核对明细'!$E$2:$E$2,MATCH(H2,'核对明细'!$C$2:$C$2,0)),\"\")"
    o1 = "IFERROR(INDEX('核对明细'!$E$2:$E$2,MATCH(I2,'核对明细'!$C$2:$C$2,0)),\"\")"
    n0 = f"IFERROR(INDEX('复核事项索引'!$B$2:$B$2,MATCH({o0},'复核事项索引'!$C$2:$C$2,0)),\"\")"
    n1 = f"IFERROR(INDEX('复核事项索引'!$B$2:$B$2,MATCH({o1},'复核事项索引'!$C$2:$C$2,0)),\"\")"
    base = "IFERROR(INDEX('复核事项索引'!$D$2:$D$2,MATCH(G2,'复核事项索引'!$C$2:$C$2,0)),\"\")"
    bl = f'IF({o0}="","未对应","已确认对应（核对"&{n0}&"）")'
    jl = f'IF({o1}="","未对应","已确认对应（核对"&{n1}&"）")'
    expected = (f'=IF(AND({o0}={o1},{o0}<>""),IF({o0}=G2,{base},"已并入核对"&{n0}&"，对应已确认"),'
                f'IF(AND({o0}="",{o1}=""),{base},"银行："&{bl}&"；序时账："&{jl}))')
    assert _值(簿.取表("逐笔核对"), 2, "当前核对结论") == expected


